def build():
    rows = []
    pid = 0
    for cat, meta in CATEGORIES.items():
        for intent, templates in INTENTS.items():
            for tpl in templates:
                pid += 1
                rows.append(
                    {
                        "prompt_id": f"P{pid:04d}",
                        "category": cat,
                        "intent": intent,
                        "template": tpl,
                        "prompt": tpl.format(c=cat),
                    }
                )

    payload = {
        "meta": {
            "categories": {k: {"brands": v["brands"], "aliases": v["aliases"]}
                           for k, v in CATEGORIES.items()},
            "intents": list(INTENTS.keys()),
            "n_prompts": len(rows),
        },
        "prompts": rows,
    }

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")

    print(f"생성 완료: {OUT}")
    print(f"  카테고리 {len(CATEGORIES)}개 × 의도 {len(INTENTS)}개 × 변형 8개 = {len(rows)}개 질의")
    for cat in CATEGORIES:
        n = sum(1 for r in rows if r["category"] == cat)
        print(f"  - {cat}: {n}개")


if __name__ == "__main__":
    build()
